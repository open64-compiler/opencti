def at_old_path(markdown):
    # Guides reside one directory below the original entry points.
    def relocate(match):
        label, target = match.groups()
        path, marker, fragment = target.partition('#')
        if path.startswith('../../'):
            path = '../' + path[6:]
        elif path.startswith('../'):
            path = path[3:]
        elif path and not urlsplit(path).scheme:
            path = 'guide/' + path
        return f'[{label}]({path}{marker}{fragment})'
    return re.sub(r'\[([^\]]+)\]\(([^)]+)\)', relocate, markdown)


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links, self.ids = [], set()

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs:
            self.ids.add(attrs['id'])
        if tag == 'a' and 'href' in attrs:
            self.links.append(attrs['href'])


def validate(outputs):
    errors, parsed = [], {}
    for path, data in outputs.items():
        if path.suffix == '.html':
            parser = Links()
            parser.feed(data)
            parsed[path] = parser
    for path, parser in parsed.items():
        for link in parser.links:
            url = urlsplit(link)
            if url.scheme or url.netloc:
                continue
            target = (path.parent / unquote(url.path)).resolve() if url.path else path
            if target not in outputs and not target.exists():
                errors.append(f'{path.relative_to(ROOT)}: missing link {link}')
            elif url.fragment and target in parsed and unquote(url.fragment) not in parsed[target].ids:
                errors.append(f'{path.relative_to(ROOT)}: missing fragment {link}')
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check reproducibility and links without writing')
    args = parser.parse_args()
    sources = {p.stem: p.read_text() for p in sorted(GUIDE.glob('*.md')) if p.stem != 'reference'}
    sources['reference'] = reference()
    outputs = {GUIDE / 'reference.md': sources['reference']}
    for name, content in sources.items():
        outputs[GUIDE / (name + '.html')] = page(content)
    for filename, (topics, aliases) in LEGACY.items():
        content = '\n\n'.join(at_old_path(sources[name]) for name in topics)
        outputs[ROOT / 'doc' / filename] = page(content, 'guide/index.html', aliases)
    landing = at_old_path(sources['index'])
    # This landing page is also served through www/index.html. Correct only
    # its guide links when the browser sees it at the web document root.
    outputs[ROOT / 'doc/index.html'] = page(landing, 'guide/index.html').replace('</body>', '''<script>
const path = location.pathname;
if (!(path.endsWith('/doc/') || path.endsWith('/doc/index.html'))) {
  document.querySelectorAll('a[href^="guide/"]').forEach(a => a.setAttribute('href', 'doc/' + a.getAttribute('href')));
}
</script></body>''')
    for filename in ['app-script.txt', 'cti-application-import.txt']:
        content = sources['adding-tests']
        outputs[ROOT / 'doc' / filename] = NOTICE + ('CTI application and test integration\n'
            'Generated from doc/guide/adding-tests.md; implementation takes precedence over prior documentation.\n'
            'Read doc/guide/adding-tests.html for clickable source links.\n\n' + content)
    errors = validate(outputs)
    if args.check:
        errors += [f'Stale output: {p.relative_to(ROOT)}' for p, data in outputs.items()
                   if not p.exists() or p.read_text() != data]
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    if not args.check:
        for path, data in outputs.items():
            path.write_text(data)
    print(f'{"Checked" if args.check else "Built"} {len(outputs)} documentation files; local links and fragments valid.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
