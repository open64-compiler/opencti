def records(path, fields):
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip() or line.startswith('#'):
            continue
        parts = line.split('@', fields - 1)
        if len(parts) != fields:
            raise ValueError(f'{path}:{number}: expected {fields} fields')
        yield number, parts


def cell(text):
    return text.replace('|', '&#124;').replace('\n', ' ')


def reference():
    lines = ['# Options and result reference', '', '[Documentation home](index.md)', '',
             'Generated by `doc/tools/build_docs.py` from the configuration files. Do not edit this page directly.', '',
             'Descriptions below reproduce source metadata verbatim, including historical terminology. They declare names and describe intent; driver code determines behavior. See [configuration](configuration.md) for loading and precedence.', '',
             '## Test-level customizable options', '',
             '[Source registry](../../conf/TestLevelCustomizableOptions.conf). The malformed literal key containing `TestLevelCustomizableOptions.conf:APP_LANG` is retained exactly as stored; do not assume it declares the ordinary `APP_LANG` key.', '',
             '| Name | Description |', '| --- | --- |']
    for _, (name, desc) in records(ROOT / 'conf/TestLevelCustomizableOptions.conf', 2):
        lines.append(f'| `{cell(name)}` | {cell(desc)} |')
    lines += ['', '## Result types', '', '[Source registry](../../conf/TestResultTypes.conf). Properties identify compile/runtime triage eligibility where declared.', '',
              '| Tag | Log label | Properties | Description |', '| --- | --- | --- | --- |']
    for _, fields in records(ROOT / 'conf/TestResultTypes.conf', 4):
        tag, label, props, desc = fields
        lines.append(f'| `{cell(tag)}` | {cell(label)} | {cell(props)} | {cell(desc)} |')
    for title, name in [('Additional saved options', 'SavedOptions.conf'), ('Options excluded from saving', 'UnsavedOptions.conf')]:
        lines += ['', '## ' + title, '', f'[Source list](../../conf/{name}).', '', '```text']
        lines += [line.strip() for line in (ROOT / 'conf' / name).read_text().splitlines()
                  if line.strip() and not line.startswith('#')]
        lines += ['```']
    return '\n'.join(lines) + '\n'


def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def inline(text):
    # Tokenize inline code/links before escaping to avoid interpreting prose as HTML.
    pattern = r'`([^`]+)`|\[([^\]]+)\]\(([^)]+)\)'
    out, start = [], 0
    for match in re.finditer(pattern, text):
        out.append(html.escape(text[start:match.start()]))
        if match.group(1) is not None:
            out.append('<code>' + html.escape(match.group(1)) + '</code>')
        else:
            url = match.group(3)
            path, marker, fragment = url.partition('#')
            if path.endswith('.md') and Path(path).name in {p.name for p in GUIDE.glob('*.md')}:
                path = path[:-3] + '.html'
            out.append(f'<a href="{html.escape(path + marker + fragment, quote=True)}">{html.escape(match.group(2))}</a>')
        start = match.end()
    out.append(html.escape(text[start:]))
    return ''.join(out)


def render(markdown):
    lines = markdown.splitlines()
    result, ids = [], set()
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
        elif line.startswith('```'):
            code = []
            i += 1
            while i < len(lines) and not lines[i].startswith('```'):
                code.append(lines[i])
                i += 1
            if i == len(lines):
                raise ValueError('Unclosed code fence')
            result.append('<pre><code>' + html.escape('\n'.join(code)) + '</code></pre>')
            i += 1
        elif re.match(r'^#{1,6} ', line):
            hashes, text = line.split(' ', 1)
            ident, counter = slug(text), 1
            base = ident
            while ident in ids:
                ident = f'{base}-{counter}'
                counter += 1
            ids.add(ident)
            result.append(f'<h{len(hashes)} id="{ident}">{inline(text)}</h{len(hashes)}>')
            i += 1
        elif line.startswith('|'):
            rows = []
            while i < len(lines) and lines[i].startswith('|'):
                rows.append([c.strip() for c in lines[i].strip().strip('|').split('|')])
                i += 1
            if len(rows) < 2 or not all(re.fullmatch(r':?-+:?', c) for c in rows[1]):
                raise ValueError('Table requires a separator row')
            result.append('<table><thead><tr>' + ''.join('<th>' + inline(c) + '</th>' for c in rows[0]) + '</tr></thead><tbody>')
            for row in rows[2:]:
                if len(row) != len(rows[0]):
                    raise ValueError('Inconsistent table column count')
                result.append('<tr>' + ''.join('<td>' + inline(c) + '</td>' for c in row) + '</tr>')
            result.append('</tbody></table>')
        elif re.match(r'^(?:- |\d+\. )', line):
            ordered = bool(re.match(r'^\d+\. ', line))
            tag, pattern = ('ol', r'^\d+\. ') if ordered else ('ul', r'^- ')
            result.append('<' + tag + '>')
            while i < len(lines) and re.match(pattern, lines[i]):
                result.append('<li>' + inline(re.sub(pattern, '', lines[i])) + '</li>')
                i += 1
            result.append('</' + tag + '>')
        else:
            paragraph = []
            while i < len(lines) and lines[i].strip():
                if lines[i].startswith(('#', '```', '|')) or re.match(r'^(?:- |\d+\. )', lines[i]):
                    break
                paragraph.append(lines[i])
                i += 1
            if not paragraph:
                raise ValueError(f'Unsupported block: {lines[i]}')
            result.append('<p>' + inline(' '.join(paragraph)) + '</p>')
    return '\n'.join(result)


def page(markdown, home='index.html', aliases=()):
    title = markdown.splitlines()[0].lstrip('# ')
    anchors = ''.join(f'<span id="{a}"></span>' for a in aliases)
    return NOTICE + f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)} — OpenCTI</title><style>{CSS}</style></head><body><main>
<nav><a href="{home}">CTI documentation</a></nav>
{anchors}{render(markdown)}
<footer>Reconstructed from OpenCTI source, baseline 8c3d603. Generated by doc/tools/build_docs.py.</footer>
</main></body></html>
'''


